/// Completes the driver task under its claim guard; a stale token rolls
/// the whole terminal back.
async fn complete_driver_task(
    txn: &mut PgConnection,
    driver_task_id: AgentDriverTaskId,
    claim_token: uuid::Uuid,
) -> Result<(), AgentRuntimeError> {
    let completed = PgAgentDriverTaskRepository
        .complete(txn, driver_task_id, claim_token)
        .await
        .map_err(|source| AgentRuntimeError::database("completing the driver task", source))?;
    if completed == 0 {
        return Err(AgentRuntimeError::LeaseLost {
            driving_task: DrivingTaskRef::Driver(driver_task_id),
        });
    }
    Ok(())
}

/// Appends the child's assistant record (when it produced one) and moves
/// it to its terminal, linking the child's committed spend to its record
/// under the thread-keyed attribution.
async fn finish_child(
    txn: &mut PgConnection,
    child: &AgentThread,
    response: Option<(&CompletionResponse, i32)>,
    terminal: AgentThreadTerminal,
) -> Result<(), AgentRuntimeError> {
    if let Some((response, attempt)) = response {
        let content = serde_json::to_value(AssistantContent {
            text: response.text.clone(),
            tool_calls: vec![],
        })
        .map_err(|source| serialisation(child, "the child's assistant content", source))?;
        let usage = serde_json::to_value(RecordedUsage::from(response))
            .map_err(|source| serialisation(child, "the child's usage", source))?;

        PgAgentThreadRepository
            .lock(txn, child.id())
            .await
            .map_err(|source| {
                AgentRuntimeError::database("locking the child for terminal", source)
            })?;
        let seq = next_seq(txn, child.id()).await?;
        let record = PgAgentThreadRecordRepository
            .append(
                txn,
                &NewAgentThreadRecord::builder()
                    .thread_id(child.id())
                    .seq(seq)
                    .kind(AgentThreadRecordKind::AssistantMessage)
                    .content(content)
                    .usage(Some(usage))
                    .trace_id(current_trace_id())
                    .span_id(current_span_id())
                    .build(),
            )
            .await
            .map_err(|source| {
                AgentRuntimeError::database("committing the child's assistant record", source)
            })?;
        // Thread-keyed attribution: the child has no stage task, so its
        // committed spend links to its record through the thread, under
        // the same single-most-recent-row constraint as the parent's.
        PgTokenUsageRepository
            .link_thread_completion_to_record(txn, child.id(), attempt, record.id())
            .await
            .map_err(|source| {
                AgentRuntimeError::database("linking the child's spend to its record", source)
            })?;
    }
    finish_child_status(txn, child, terminal).await
}

/// Moves the child to a terminal status. A death path carries no
/// assistant record (the child produced no result), so the status move
/// stands alone.
async fn finish_child_status(
    txn: &mut PgConnection,
    child: &AgentThread,
    terminal: AgentThreadTerminal,
) -> Result<(), AgentRuntimeError> {
    let moved = PgAgentThreadRepository
        .complete(txn, child.id(), terminal, AgentThreadStatus::Running)
        .await
        .map_err(|source| AgentRuntimeError::database("completing the child thread", source))?;
    if moved == 0 {
        return Err(AgentRuntimeError::StatusCasMissed {
            thread_id: child.id(),
            expected: AgentThreadStatus::Running,
        });
    }
    Ok(())
}

/// Hands the result back to the parent: under the parent row lock, a
/// suspended parent takes the fenced tool-result and wakes; a parent no
/// longer waiting discards the hand-back. The parent lock is the orphan
/// guard.
async fn hand_back(
    txn: &mut PgConnection,
    parent: &ParentResolution,
    result: &ToolResultContent,
) -> Result<ChildTerminalOutcome, AgentRuntimeError> {
    let Some(locked) = PgAgentThreadRepository
        .lock(txn, parent.thread_id)
        .await
        .map_err(|source| {
            AgentRuntimeError::database("locking the parent for hand-back", source)
        })?
    else {
        return Ok(ChildTerminalOutcome::ParentNotWaiting);
    };
    if locked.status() != AgentThreadStatus::Suspended {
        // The orphan window: a cancelled or already-resolved parent is
        // not waiting. The child and driver still committed above; the
        // hand-back discards.
        return Ok(ChildTerminalOutcome::ParentNotWaiting);
    }

    let content = serde_json::to_value(result).map_err(|source| {
        serialisation_id(parent.thread_id, "the hand-back tool result", source)
    })?;
    let seq = next_seq(txn, parent.thread_id).await?;
    PgAgentThreadRecordRepository
        .append(
            txn,
            &NewAgentThreadRecord::builder()
                .thread_id(parent.thread_id)
                .seq(seq)
                .kind(AgentThreadRecordKind::ToolResult)
                .requesting_seq(Some(parent.requesting_seq))
                .tool_call_id(Some(parent.tool_call_id.clone()))
                .content(content)
                .trace_id(current_trace_id())
                .span_id(current_span_id())
                .build(),
        )
        .await
        .map_err(|source| {
            AgentRuntimeError::database("committing the parent's hand-back result", source)
        })?;

    let woken = PgAgentThreadRepository
        .mark_running(txn, parent.thread_id, AgentThreadStatus::Suspended)
        .await
        .map_err(|source| AgentRuntimeError::database("waking the parent", source))?;
    if woken == 0 {
        return Err(AgentRuntimeError::StatusCasMissed {
            thread_id: parent.thread_id,
            expected: AgentThreadStatus::Suspended,
        });
    }
    if let Some(task_id) = locked.stage_task_id() {
        let rows = PgTaskRepository
            .requeue_from_blocked(txn, task_id)
            .await
            .map_err(|source| AgentRuntimeError::database("re-queueing the parent task", source))?;
        if rows == 0 {
            // The parent's task is blocked by construction while a child
            // drives, so a zero-row requeue would leave it running with an
            // unclaimable task; roll the hand-back back rather than strand
            // it.
            return Err(AgentRuntimeError::DrivingTaskNotBlocked { task_id });
        }
    }
    Ok(ChildTerminalOutcome::HandedBack)
}

async fn next_seq(
    txn: &mut PgConnection,
    thread_id: AgentThreadId,
) -> Result<AgentThreadRecordSeq, AgentRuntimeError> {
    PgAgentThreadRecordRepository
        .next_seq(txn, thread_id)
        .await
        .map_err(|source| AgentRuntimeError::database("deriving the next seq", source))
}

fn serialise_suspension(
    thread: &AgentThread,
    suspension: &AgentThreadSuspension,
) -> Result<serde_json::Value, AgentRuntimeError> {
    serde_json::to_value(suspension)
        .map_err(|source| serialisation(thread, "the suspension record", source))
}

fn serialisation(thread: &AgentThread, what: &str, source: serde_json::Error) -> AgentRuntimeError {
    serialisation_id(thread.id(), what, source)
}

fn serialisation_id(
    thread_id: AgentThreadId,
    what: &str,
    source: serde_json::Error,
) -> AgentRuntimeError {
    AgentRuntimeError::ContentSerialisation {
        context: format!("serialising {what} of thread {thread_id}"),
        source,
    }
}
